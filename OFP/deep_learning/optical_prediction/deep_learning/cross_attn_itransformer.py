# ── shared helpers ───────────────────────────────────────────────────
def _mask_aware_norm(x: torch.Tensor, mask: torch.Tensor):
    denom = mask.sum(dim=1, keepdim=True).clamp(min=1.0)
    mean = (x * mask).sum(dim=1, keepdim=True) / denom
    var = ((x - mean) ** 2 * mask).sum(dim=1, keepdim=True) / denom
    std = torch.sqrt(var + 1e-5)
    return (x - mean) / std * mask


def _build_encoder(cfg, output_attention: bool = False):
    enc_embedding = DataEmbedding_inverted(
        cfg.seq_len, cfg.d_model, cfg.embed, cfg.freq, cfg.dropout,
    )
    encoder = Encoder(
        [
            EncoderLayer(
                AttentionLayer(
                    FullAttention(
                        False, cfg.factor,
                        attention_dropout=cfg.dropout,
                        output_attention=output_attention,
                    ),
                    cfg.d_model, cfg.n_heads,
                ),
                cfg.d_model, cfg.d_ff,
                dropout=cfg.dropout, activation=cfg.activation,
            )
            for _ in range(cfg.e_layers)
        ],
        norm_layer=nn.LayerNorm(cfg.d_model),
    )
    return enc_embedding, encoder


# ── AdaLN: Adaptive Layer Normalization (MTPNet §3.2.2) ──────────────
class AdaptiveLayerNorm(nn.Module):
    """Layer Normalization whose affine parameters (γ, β) are dynamically
    generated by an external conditioning signal.

    Implements:  AdaLN(x, cond) = γ(cond) ⊙ LayerNorm(x) + β(cond)
    """

    def __init__(self, d_model: int, cond_dim: int) -> None:
        super().__init__()
        self.norm = nn.LayerNorm(d_model, elementwise_affine=False)
        self.weight_regressor = nn.Linear(cond_dim, d_model * 2)
        nn.init.zeros_(self.weight_regressor.bias)
        # Initialize γ ≈ 1, β ≈ 0
        with torch.no_grad():
            self.weight_regressor.weight.zero_()
            self.weight_regressor.bias[:d_model].fill_(1.0)

    def forward(self, x: torch.Tensor, cond: torch.Tensor) -> torch.Tensor:
        """x: (B, N, d), cond: (B, cond_dim) → (B, N, d)."""
        params = self.weight_regressor(cond)               # (B, 2d)
        gamma, beta = params.chunk(2, dim=-1)               # each (B, d)
        return gamma.unsqueeze(1) * self.norm(x) + beta.unsqueeze(1)


# ── Feature Abstractor (MTPNet §3.2.2) ───────────────────────────────
class FeatureAbstractor(nn.Module):
    """Compress a set of tokens into a single global semantic vector via
    attention-weighted pooling + linear projection."""

    def __init__(self, d_model: int, d_out: int, dropout: float = 0.1) -> None:
        super().__init__()
        self.attn_score = nn.Linear(d_model, 1, bias=False)
        self.proj = nn.Sequential(
            nn.Linear(d_model, d_out),
            nn.GELU(),
            nn.Dropout(dropout),
        )

    def forward(self, tokens: torch.Tensor) -> torch.Tensor:
        """tokens: (B, N, d) → (B, d_out)."""
        alpha = F.softmax(self.attn_score(tokens), dim=1)   # (B, N, 1)
        pooled = (tokens * alpha).sum(dim=1)                # (B, d)
        return self.proj(pooled)                             # (B, d_out)


# ── Single MFP Layer ─────────────────────────────────────────────────
class MFPLayer(nn.Module):
    """One layer of Multi-grained Fault Perception.

    Combines:
      MFS (Macro-level Fault Semantic): AdaLN conditioning → Self-Attention
      MPS (Micro-level Pattern Semantic): Bidirectional cross-attention
    """

    def __init__(self, d_model: int, n_heads: int, d_ff: int,
                 n_concepts: int, dropout: float) -> None:
        super().__init__()

        # ── MFS: Macro-level Fault Semantic guidance ──
        self.feature_abstractor = FeatureAbstractor(d_model, d_model, dropout)
        self.adaln = AdaptiveLayerNorm(d_model, cond_dim=d_model)
        self.self_attn = nn.MultiheadAttention(
            embed_dim=d_model, num_heads=n_heads,
            dropout=dropout, batch_first=True,
        )
        self.norm_sa = nn.LayerNorm(d_model)

        # ── MPS: Micro-level Pattern Semantic guidance ──
        # Cross-attention 1: concepts query sensors
        self.cross_attn_c2s = nn.MultiheadAttention(
            embed_dim=d_model, num_heads=n_heads,
            dropout=dropout, batch_first=True,
        )
        self.norm_c2s = nn.LayerNorm(d_model)
        self.ffn_concept = nn.Sequential(
            nn.Linear(d_model, d_ff), nn.GELU(), nn.Dropout(dropout),
            nn.Linear(d_ff, d_model), nn.Dropout(dropout),
        )
        self.norm_c_ffn = nn.LayerNorm(d_model)

        # Cross-attention 2: sensors query concepts
        self.cross_attn_s2c = nn.MultiheadAttention(
            embed_dim=d_model, num_heads=n_heads,
            dropout=dropout, batch_first=True,
        )
        self.norm_s2c = nn.LayerNorm(d_model)
        self.ffn_sensor = nn.Sequential(
            nn.Linear(d_model, d_ff), nn.GELU(), nn.Dropout(dropout),
            nn.Linear(d_ff, d_model), nn.Dropout(dropout),
        )
        self.norm_s_ffn = nn.LayerNorm(d_model)

    def forward(self, sensor_tokens: torch.Tensor, concept_tokens: torch.Tensor,
                attn_bias: torch.Tensor | None = None):
        """
        sensor_tokens : (B, N, d)
        concept_tokens: (B, K, d)
        attn_bias     : (K, N) optional additive bias for concept→sensor attention
        Returns:
            sensor_out  : (B, N, d) – refined sensor tokens
            concept_out : (B, K, d) – refined concept tokens
            attn_c2s    : (B, K, N) – concept→sensor attention weights
            attn_s2c    : (B, N, K) – sensor→concept attention weights
        """
        # ── MFS: global conditioning + self-attention ──
        global_cond = self.feature_abstractor(sensor_tokens)  # (B, d)
        z_cond = self.adaln(sensor_tokens, global_cond)       # (B, N, d)
        z_sa, _ = self.self_attn(z_cond, z_cond, z_cond)     # (B, N, d)
        sensor_tokens = self.norm_sa(z_sa + sensor_tokens)    # residual

        # ── MPS step 1: concepts query sensors ──
        c_repr, attn_c2s = self.cross_attn_c2s(
            query=concept_tokens, key=sensor_tokens, value=sensor_tokens,
            attn_mask=attn_bias,
        )  # c_repr: (B, K, d), attn_c2s: (B, K, N)
        concept_out = self.norm_c2s(c_repr + concept_tokens)
        concept_out = self.norm_c_ffn(concept_out + self.ffn_concept(concept_out))

        # ── MPS step 2: sensors query concepts ──
        s_repr, attn_s2c = self.cross_attn_s2c(
            query=sensor_tokens, key=concept_out, value=concept_out,
        )  # s_repr: (B, N, d), attn_s2c: (B, N, K)
        sensor_out = self.norm_s2c(s_repr + sensor_tokens)
        sensor_out = self.norm_s_ffn(sensor_out + self.ffn_sensor(sensor_out))

        return sensor_out, concept_out, attn_c2s, attn_s2c


# ── Config ────────────────────────────────────────────────────────────
@dataclass
class CrossAttnITransformerCfg:
    seq_len: int = 288
    n_sensors: int = 12
    use_mask_channel: bool = True
    d_model: int = 128
    n_heads: int = 8
    e_layers: int = 3
    d_ff: int = 256
    dropout: float = 0.2
    activation: str = "gelu"
    factor: int = 1
    use_norm: bool = True
    embed: str = "fixed"
    freq: str = "h"
    # Cross-attention / MFP specific
    concept_names: List[str] = field(default_factory=lambda: [
        "thermal_anomaly", "current_bias_anomaly", "tx_power_anomaly",
        "rx_power_anomaly", "lane_imbalance",
    ])
    n_concepts: int = 5
    concept_dropout: float = 0.1
    # How much residual bypass from mean-pooled encoder output
    bypass_ratio: float = 0.3
    # Number of stacked MFP layers (MTPNet-inspired iterative refinement)
    n_mfp_layers: int = 2


# ── L4 Model ──────────────────────────────────────────────────────────
class L4_CrossAttnITransformer(nn.Module):
    """Multi-grained Fault Perception iTransformer (MTPNet-inspired).

    Stacks multiple MFP layers that alternate:
      - MFS: AdaLN-conditioned self-attention (global fault pattern guidance)
      - MPS: bidirectional cross-attention (fine-grained concept-sensor interaction)

    Forward returns (logit, sensor_importance, concept_sensor_attn,
                     sensor_concept_attn, concept_activations) so every
    downstream visualisation script can consume the same tuple indices.
    """

    def __init__(self, cfg: CrossAttnITransformerCfg) -> None:
        super().__init__()
        self.cfg = cfg
        self.use_mask_channel = cfg.use_mask_channel
        self.use_norm = cfg.use_norm
        self.enc_embedding, self.encoder = _build_encoder(
            cfg, output_attention=True
        )

        # Learnable concept embeddings
        n_concepts = cfg.n_concepts
        self.concept_queries = nn.Parameter(
            torch.randn(n_concepts, cfg.d_model) * 0.02
        )
        nn.init.xavier_uniform_(self.concept_queries.data.unsqueeze(0))

        # Stacked MFP layers
        self.mfp_layers = nn.ModuleList([
            MFPLayer(cfg.d_model, cfg.n_heads, cfg.d_ff,
                     n_concepts, cfg.dropout)
            for _ in range(cfg.n_mfp_layers)
        ])

        # Bypass path: mean-pool raw encoder output for gradient flow
        bypass_dim = max(4, n_concepts // 2)
        self.bypass_proj = nn.Sequential(
            nn.Linear(cfg.d_model, bypass_dim),
            nn.GELU(),
        )

        # Final head takes enriched sensor tokens + bypass
        head_in = cfg.d_model + bypass_dim
        self.head = nn.Sequential(
            nn.LayerNorm(head_in),
            nn.Linear(head_in, head_in // 2),
            nn.GELU(),
            nn.Dropout(cfg.dropout),
            nn.Linear(head_in // 2, 1),
        )

    def forward(self, x: torch.Tensor, mask: torch.Tensor):
        # -- input preparation (same as baseline) --
        if self.use_mask_channel:
            inp = torch.cat([x, mask], dim=-1)
        else:
            inp = x
        if self.use_norm:
            x_norm = _mask_aware_norm(x, mask)
            inp = torch.cat([x_norm, mask], dim=-1) if self.use_mask_channel else x_norm

        enc_out = self.enc_embedding(inp, None)          # (B, C, d)
        enc_out, _self_attns = self.encoder(enc_out, attn_mask=None)

        n_s = self.cfg.n_sensors
        sensor_tokens = enc_out[:, :n_s, :]               # (B, N, d)
        # Save raw encoder output for bypass before MFP refinement
        sensor_tokens_raw = sensor_tokens

        B = sensor_tokens.size(0)
        concept_tokens = self.concept_queries.unsqueeze(0).expand(B, -1, -1)

        # ── Stacked MFP layers ──
        # We keep the last layer's attention maps for downstream visualisation.
        attn_c2s_last = None
        attn_s2c_last = None
        for mfp in self.mfp_layers:
            sensor_tokens, concept_tokens, attn_c2s_last, attn_s2c_last = \
                mfp(sensor_tokens, concept_tokens)

        # ── Pooling & classification ──
        pooled = sensor_tokens.mean(dim=1)                          # (B, d)
        bypass = self.bypass_proj(sensor_tokens_raw.mean(dim=1))    # (B, bypass_dim)
        bypass = bypass * self.cfg.bypass_ratio
        combined = torch.cat([pooled, bypass], dim=-1)              # (B, d+bypass_dim)
        logit = self.head(combined).squeeze(-1)                     # (B,)

        # ── Aggregate sensor importance from attention maps ──
        # Mean over concepts: each concept's attention to sensors, averaged
        sensor_importance = attn_c2s_last.mean(dim=1)               # (B, N)
        sensor_importance = sensor_importance / sensor_importance.sum(
            dim=-1, keepdim=True
        ).clamp(min=1e-8)

        return logit, sensor_importance, attn_c2s_last, attn_s2c_last


class L4_TypeAwareCrossAttnITransformer(nn.Module):
    """Type-aware L4 variant with weak multi-task fault-type supervision.

    The MFP concept tokens are aligned with weak optical-module fault types.
    Besides the main fault-risk logit, the model returns one type logit per
    concept.  The main risk head also consumes those type logits, so auxiliary
    type learning can affect prediction instead of only post-hoc explanation.
    """

    def __init__(self, cfg: CrossAttnITransformerCfg) -> None:
        super().__init__()
        self.cfg = cfg
        self.use_mask_channel = cfg.use_mask_channel
        self.use_norm = cfg.use_norm
        self.enc_embedding, self.encoder = _build_encoder(
            cfg, output_attention=True
        )

        n_concepts = cfg.n_concepts
        self.concept_queries = nn.Parameter(
            torch.randn(n_concepts, cfg.d_model) * 0.02
        )
        nn.init.xavier_uniform_(self.concept_queries.data.unsqueeze(0))

        self.mfp_layers = nn.ModuleList([
            MFPLayer(cfg.d_model, cfg.n_heads, cfg.d_ff,
                     n_concepts, cfg.dropout)
            for _ in range(cfg.n_mfp_layers)
        ])

        bypass_dim = max(4, n_concepts // 2)
        self.bypass_proj = nn.Sequential(
            nn.Linear(cfg.d_model, bypass_dim),
            nn.GELU(),
        )
        self.type_head = nn.Linear(cfg.d_model, 1)

        head_in = cfg.d_model + bypass_dim + n_concepts
        self.head = nn.Sequential(
            nn.LayerNorm(head_in),
            nn.Linear(head_in, head_in // 2),
            nn.GELU(),
            nn.Dropout(cfg.dropout),
            nn.Linear(head_in // 2, 1),
        )

    def forward(self, x: torch.Tensor, mask: torch.Tensor):
        if self.use_mask_channel:
            inp = torch.cat([x, mask], dim=-1)
        else:
            inp = x
        if self.use_norm:
            x_norm = _mask_aware_norm(x, mask)
            inp = torch.cat([x_norm, mask], dim=-1) if self.use_mask_channel else x_norm

        enc_out = self.enc_embedding(inp, None)
        enc_out, _self_attns = self.encoder(enc_out, attn_mask=None)

        n_s = self.cfg.n_sensors
        sensor_tokens = enc_out[:, :n_s, :]
        sensor_tokens_raw = sensor_tokens

        B = sensor_tokens.size(0)
        concept_tokens = self.concept_queries.unsqueeze(0).expand(B, -1, -1)

        attn_c2s_last = None
        attn_s2c_last = None
        for mfp in self.mfp_layers:
            sensor_tokens, concept_tokens, attn_c2s_last, attn_s2c_last = \
                mfp(sensor_tokens, concept_tokens)

        type_logits = self.type_head(concept_tokens).squeeze(-1)
        # Use gated probabilities (not raw logits) in head so that type
        # classification loss shapes the attention maps through the gate.
        concept_gate = torch.sigmoid(type_logits)
        pooled = sensor_tokens.mean(dim=1)
        bypass = self.bypass_proj(sensor_tokens_raw.mean(dim=1))
        bypass = bypass * self.cfg.bypass_ratio
        combined = torch.cat([pooled, bypass, concept_gate], dim=-1)
        logit = self.head(combined).squeeze(-1)

        # Sensor importance: weighted sum of concept-to-sensor attention,
        # gated by concept activation probabilities.
        sensor_importance = torch.bmm(
            concept_gate.unsqueeze(1), attn_c2s_last
        ).squeeze(1)
        gate_sum = concept_gate.sum(dim=-1, keepdim=True)
        fallback = attn_c2s_last.mean(dim=1)
        sensor_importance = torch.where(
            gate_sum > 1e-6,
            sensor_importance / gate_sum.clamp(min=1e-6),
            fallback,
        )
        sensor_importance = sensor_importance / sensor_importance.sum(
            dim=-1, keepdim=True
        ).clamp(min=1e-8)

        return logit, sensor_importance, attn_c2s_last, attn_s2c_last, type_logits
