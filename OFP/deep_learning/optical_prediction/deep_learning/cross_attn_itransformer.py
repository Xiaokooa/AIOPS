"""Cross-Attention interpretable iTransformer (L4 variant).

Inspired by Multi-Grained Target Perception (MTPNet, arXiv:2506.05427):
a Multi-grained Fault Perception (MFP) module iteratively refines sensor
representations through alternating:
  - Macro-level Fault Semantic (MFS) guidance: AdaLN conditioning +
    self-attention captures global degradation patterns.
  - Micro-level Pattern Semantic (MPS) guidance: bidirectional cross-attention
    between sensor tokens and learnable concept queries captures fine-grained
    fault-specific interactions.

Architecture:
  1. iTransformer encoder -> sensor tokens Z (B, N, d)
  2. MFP Module (stacked L_mfp layers, each containing):
     a. MFS: Feature Abstractor(Z) → Weight Regressor → (γ,β)
             → AdaLN(Z, γ, β) → Self-Attention → Z'
     b. MPS: Concept queries cross-attend Z' → concept_repr
             Z' cross-attends concept_repr → Z'' (enriched)
             + FFN + residual
  3. Pool over Z_final + bypass → classification head

All attention maps from the **last** MFP layer are returned so downstream
code can visualise which sensors/concepts drove each prediction.
The output tuple format is identical to the original L4 for compatibility:
(logit, sensor_importance, concept_sensor_attn, sensor_concept_attn,
 concept_activations).
"""
